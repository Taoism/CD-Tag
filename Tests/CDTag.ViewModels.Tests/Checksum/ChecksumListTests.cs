using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using CDTag.Model.Checksum;
using NUnit.Framework;

namespace CDTag.ViewModel.Tests.Checksum
{
    [TestFixture]
    public class ChecksumListTests
    {
        private string _root;

        [SetUp]
        public void CreateRoot()
        {
            _root = Path.Combine(Path.GetTempPath(), string.Concat("cdtag-checksum-", Guid.NewGuid().ToString("N").AsSpan(0, 8)));
            Directory.CreateDirectory(_root);
        }

        [TearDown]
        public void DeleteRoot()
        {
            Directory.Delete(_root, true);
        }

        private string Write(string name, string content)
        {
            string path = Path.Combine(_root, name);
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, content, new UTF8Encoding(false));
            return path;
        }

        [Test]
        public void Compute_KnownValues()
        {
            string file = Write("check.bin", "123456789");
            Assert.That(ChecksumList.Compute(file, ChecksumKind.Sfv), Is.EqualTo("CBF43926"));
            string abc = Write("abc.bin", "abc");
            Assert.That(ChecksumList.Compute(abc, ChecksumKind.Md5), Is.EqualTo("900150983cd24fb0d6963f7d28e17f72"));
            Assert.That(ChecksumList.Compute(abc, ChecksumKind.Sha1), Is.EqualTo("a9993e364706816aba3e25717850c26c9cd0d89d"));
        }

        [Test]
        public void ParseSfv_SkipsCommentsAndKeepsSpacesInNames()
        {
            const string text = "; Generated by CD-Tag on 2026-11-03 at 10:00.00\r\n" +
                                ";      1234567  10:00.00 2026-11-03 01-artist-song.flac\r\n" +
                                "01-artist-song.flac 0a1b2c3d\r\n" +
                                "CD2/02 two words.flac DEADBEEF\r\n" +
                                "\r\n" +
                                "garbage line\r\n";
            List<ChecksumEntry> entries = ChecksumList.Parse(text, ChecksumKind.Sfv);
            Assert.That(entries.Select(e => e.FileName), Is.EqualTo(new[] { "01-artist-song.flac", @"CD2\02 two words.flac" }));
            Assert.That(entries[0].Hash, Is.EqualTo("0A1B2C3D"));
        }

        [Test]
        public void ParseMd5_GnuAndBsdStyles()
        {
            const string text = "# comment\n" +
                                "900150983cd24fb0d6963f7d28e17f72 *01 - a.flac\n" +
                                "900150983CD24FB0D6963F7D28E17F72  02 - b.flac\n" +
                                "MD5 (03 - c.flac) = 900150983cd24fb0d6963f7d28e17f72\n" +
                                "a9993e364706816aba3e25717850c26c9cd0d89d *sha1-in-md5-file.flac\n";
            List<ChecksumEntry> entries = ChecksumList.Parse(text, ChecksumKind.Md5);
            Assert.That(entries.Select(e => e.FileName), Is.EqualTo(new[] { "01 - a.flac", "02 - b.flac", "03 - c.flac" }));
            Assert.That(entries.All(e => e.Hash == "900150983cd24fb0d6963f7d28e17f72"));
        }

        [TestCase(ChecksumKind.Sfv)]
        [TestCase(ChecksumKind.Md5)]
        [TestCase(ChecksumKind.Sha1)]
        public void Build_ThenParse_RoundTrips(ChecksumKind kind)
        {
            var files = new[] { Write("01 one.flac", "one"), Write(@"CD2\02 two.flac", "two") };
            List<ChecksumItem> items = files.Select(f => new ChecksumItem { Path = f, Hash = ChecksumList.Compute(f, kind) }).ToList();
            string listPath = Path.Combine(_root, "album" + ChecksumList.GetExtension(kind));
            File.WriteAllBytes(listPath, ChecksumList.Build(kind, items, _root));

            List<ChecksumEntry> entries = ChecksumList.Parse(listPath);
            Assert.That(entries.Select(e => e.FileName), Is.EqualTo(new[] { "01 one.flac", @"CD2\02 two.flac" }));
            for (int i = 0; i < files.Length; i++)
                Assert.That(ChecksumList.HashEquals(entries[i].Hash, ChecksumList.Compute(Path.Combine(_root, entries[i].FileName), kind)));
        }

        [Test]
        public void Build_UsesUtf8OnlyWhenNamesDoNotFitWindows1252()
        {
            string latin = Write("Café.flac", "x");
            byte[] ansi = ChecksumList.Build(ChecksumKind.Sfv, new[] { new ChecksumItem { Path = latin, Hash = "00000000" } }, _root, true, true);
            Assert.That(ansi, Is.EqualTo(new byte[] { (byte)'C', (byte)'a', (byte)'f', 0xE9 }.Concat(Encoding.ASCII.GetBytes(".flac 00000000\r\n")).ToArray()));

            string japanese = Write("日本.flac", "x");
            byte[] utf8 = ChecksumList.Build(ChecksumKind.Sfv, new[] { new ChecksumItem { Path = japanese, Hash = "00000000" } }, _root, true, true);
            Assert.That(utf8.Take(3), Is.EqualTo(new byte[] { 0xEF, 0xBB, 0xBF }));
            Assert.That(ChecksumList.ReadText(utf8), Is.EqualTo("日本.flac 00000000\r\n"));
            Assert.That(ChecksumList.ReadText(ansi), Is.EqualTo("Café.flac 00000000\r\n"));
        }
    }
}

namespace CDTag.Model.Profile
{
    /// <summary>What Finish does with one kind of tag (CD-Tag 2.x [TAGGING] values).</summary>
    public enum TagAction
    {
        /// <summary>Write the tag, creating it when the file has none.</summary>
        WriteAlways,
        /// <summary>Update the tag only when the file already has one.</summary>
        WriteIfExists,
        /// <summary>Remove the tag.</summary>
        Remove,
        /// <summary>Leave the tag as it is.</summary>
        Leave
    }

    /// <summary>Tag writing, playlist and checksum options used by Finish.</summary>
    public class TaggingOptions
    {
        public TaggingOptions()
        {
            Id3v2 = TagAction.WriteAlways;
            Id3v1 = TagAction.WriteAlways;
            FlacId3v2 = TagAction.Remove;
            FlacId3v1 = TagAction.Remove;
            LongTrackNumbers = true;
            SeparatePlaylistPerDisc = true;
        }

        /// <summary>ID3v2 in MP3 files.</summary>
        public TagAction Id3v2 { get; set; }

        /// <summary>ID3v1 in MP3 files.</summary>
        public TagAction Id3v1 { get; set; }

        /// <summary>ID3v2 found in FLAC files (FLAC uses Vorbis comments).</summary>
        public TagAction FlacId3v2 { get; set; }

        /// <summary>ID3v1 found in FLAC files.</summary>
        public TagAction FlacId3v1 { get; set; }

        /// <summary>Track numbers as "1/12" (and discs as "1/2").</summary>
        public bool LongTrackNumbers { get; set; }

        /// <summary>Do not write the comment into ID3v2 tags.</summary>
        public bool NoId3v2Comment { get; set; }

        /// <summary>Write the comment into ID3v1 tags.</summary>
        public bool UseId3v1Comment { get; set; }

        /// <summary>Multi-disc albums get one playlist per disc.</summary>
        public bool SeparatePlaylistPerDisc { get; set; }

        /// <summary>Leave the "Generated by" header out of SFV/MD5 files.</summary>
        public bool ChecksumHideGeneratedBy { get; set; }

        /// <summary>Leave the file size/date lines out of SFV files.</summary>
        public bool ChecksumHideFileInfo { get; set; }
    }
}
